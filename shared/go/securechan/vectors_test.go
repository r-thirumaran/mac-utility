var update = flag.Bool("update", false, "regenerate shared/testdata/edgehop/handshake-vectors.json")

const vectorsPath = "../../testdata/edgehop/handshake-vectors.json"

type vectorSide struct {
	StaticPriv string `json:"staticPriv"`
	StaticPub  string `json:"staticPub"`
	ID         string `json:"id"`
	Name       string `json:"name"`
	Plat       string `json:"plat"`
	EphPriv    string `json:"ephPriv"`
	EphPub     string `json:"ephPub"`
	Rand       string `json:"rand"`
}

type vector struct {
	Name             string     `json:"name"`
	Pairing          bool       `json:"pairing"`
	Initiator        vectorSide `json:"initiator"`
	Acceptor         vectorSide `json:"acceptor"`
	Code             string     `json:"code"`
	Hello            string     `json:"hello"`
	HelloAck         string     `json:"helloAck"`
	DH1              string     `json:"dh1"`
	DH2              string     `json:"dh2"`
	DH3              string     `json:"dh3"`
	PSK              string     `json:"psk"`
	Transcript       string     `json:"transcript"`
	KeyInitToAcc     string     `json:"keyInitToAcc"`
	KeyAccToInit     string     `json:"keyAccToInit"`
	AuthPlaintext    string     `json:"authPlaintext"`
	AuthCiphertext   string     `json:"authCiphertext"`
	AuthOkPlaintext  string     `json:"authOkPlaintext"`
	AuthOkCiphertext string     `json:"authOkCiphertext"`
}

type vectorFile struct {
	Description []string `json:"description"`
	Vectors     []vector `json:"vectors"`
}

var vectorDescription = []string{
	"Edgehop v1 handshake vectors generated by `go test ./shared/go/securechan -update` (docs/edgehop-protocol.md §3-§4).",
	"All byte strings are lowercase hex except hello/helloAck, which are the exact UTF-8 JSON payloads as sent (without the 4-byte length prefix).",
	"rand: the bytes each side's Options.Rand yields, in order. Initiator: 32-byte ephemeral private key. Acceptor: in a pairing handshake 4 bytes for the code (code = u32be % 1000000, zero-padded to 6 digits) and then the 32-byte ephemeral private key; otherwise just the ephemeral key.",
	"Private keys are raw X25519 scalars; implementations clamp them as usual. Public keys are X25519(priv, basepoint).",
	"psk is 32 zero bytes for a trusted handshake, else HKDF-SHA256(ikm=code, salt=\"edgehop-pair\", info=min(id)||max(id), 32).",
	"transcript = SHA-256(\"edgehop-v1\" || hello || helloAck). okm = HKDF-SHA256(ikm=dh1||dh2||dh3||psk, salt=transcript, info=\"edgehop-v1-keys\", 64); keyInitToAcc = okm[0:32], keyAccToInit = okm[32:64].",
	"authCiphertext = ChaCha20-Poly1305(keyInitToAcc, nonce=0x00000000||u64be(0), authPlaintext, aad=\"\"); authOkCiphertext likewise with keyAccToInit and counter 0. The plaintexts are the type byte 0x01 followed by the control JSON.",
}

// recordConn records every frame (minus the length prefix) written through it.
type recordConn struct {
	net.Conn
	mu     sync.Mutex
	frames [][]byte
}

func (r *recordConn) Write(p []byte) (int, error) {
	r.mu.Lock()
	if len(p) >= 4 {
		r.frames = append(r.frames, append([]byte(nil), p[4:]...))
	}
	r.mu.Unlock()
	return r.Conn.Write(p)
}

func (r *recordConn) frame(i int) []byte {
	r.mu.Lock()
	defer r.mu.Unlock()
	if i < len(r.frames) {
		return r.frames[i]
	}
	return nil
}

func mustHex(t *testing.T, s string) []byte {
	t.Helper()
	b, err := hex.DecodeString(s)
	if err != nil {
		t.Fatalf("bad hex %q: %v", s, err)
	}
	return b
}

func key32(t *testing.T, s string) [32]byte {
	t.Helper()
	var k [32]byte
	b := mustHex(t, s)
	if len(b) != 32 {
		t.Fatalf("%q is %d bytes, want 32", s, len(b))
	}
	copy(k[:], b)
	return k
}

func seed(label string) string {
	s := sha256.Sum256([]byte("edgehop-vectors/" + label))
	return hex.EncodeToString(s[:])
}

func seedKey(label string) [32]byte {
	return sha256.Sum256([]byte("edgehop-vectors/" + label))
}

// newVectorInputs builds the fixed inputs of one vector from deterministic seeds.
func newVectorInputs(name string, pairing bool) vector {
	initStatic := IdentityFromPriv(seedKey("initiator/static"))
	accStatic := IdentityFromPriv(seedKey("acceptor/static"))
	initEph := seed("initiator/ephemeral/" + name)
	accEph := seed("acceptor/ephemeral/" + name)
	v := vector{Name: name, Pairing: pairing}
	v.Initiator = vectorSide{
		StaticPriv: hex.EncodeToString(initStatic.Priv[:]), StaticPub: hex.EncodeToString(initStatic.Pub[:]),
		ID: initStatic.ID(), Name: "Vector Mac", Plat: "macos", EphPriv: initEph, Rand: initEph,
	}
	v.Acceptor = vectorSide{
		StaticPriv: hex.EncodeToString(accStatic.Priv[:]), StaticPub: hex.EncodeToString(accStatic.Pub[:]),
		ID: accStatic.ID(), Name: "Vector PC", Plat: "windows", EphPriv: accEph, Rand: accEph,
	}
	if pairing {
		v.Acceptor.Rand = seed("code/" + name)[:8] + accEph
	}
	return v
}

// runVector executes the handshake with the vector's fixed inputs and fills in
// every derived field. Derived values are computed twice: by the handshake
// itself (observed on the wire) and from the spec formulas (helpers), and
// must agree.
func runVector(t *testing.T, in vector) vector {
	t.Helper()
	out := in
	initID := IdentityFromPriv(key32(t, in.Initiator.StaticPriv))
	accID := IdentityFromPriv(key32(t, in.Acceptor.StaticPriv))
	initTrust, accTrust := NewMemoryTrust(), NewMemoryTrust()
	if !in.Pairing {
		_ = initTrust.Trust(PeerInfo{ID: accID.ID(), Name: in.Acceptor.Name, Plat: in.Acceptor.Plat, StaticPub: accID.Pub})
		_ = accTrust.Trust(PeerInfo{ID: initID.ID(), Name: in.Initiator.Name, Plat: in.Initiator.Plat, StaticPub: initID.Pub})
	}
	codes := make(chan string, 1)
	iRaw, aRaw := net.Pipe()
	iConn, aConn := &recordConn{Conn: iRaw}, &recordConn{Conn: aRaw}
	iOpts := Options{Self: initID, Name: in.Initiator.Name, Plat: in.Initiator.Plat, Trust: initTrust, Pair: in.Pairing,
		Rand: bytes.NewReader(mustHex(t, in.Initiator.Rand)), AskCode: func() (string, error) { return <-codes, nil }}
	aOpts := Options{Self: accID, Name: in.Acceptor.Name, Plat: in.Acceptor.Plat, Trust: accTrust,
		Rand: bytes.NewReader(mustHex(t, in.Acceptor.Rand)), ShowCode: func(c string, _ PeerInfo) { out.Code = c; codes <- c }}
	type res struct {
		ch  *Channel
		err error
	}
	done := make(chan res, 1)
	go func() {
		ch, _, err := Initiate(iConn, iOpts)
		done <- res{ch, err}
	}()
	aCh, _, aErr := Accept(aConn, aOpts)
	iRes := <-done
	if aErr != nil || iRes.err != nil {
		t.Fatalf("vector %s: acceptor %v, initiator %v", in.Name, aErr, iRes.err)
	}
	aCh.Close()
	iRes.ch.Close()

	hello, ack := iConn.frame(0), aConn.frame(0)
	authCT, authOkCT := iConn.frame(1), aConn.frame(1)
	if hello == nil || ack == nil || authCT == nil || authOkCT == nil {
		t.Fatalf("vector %s: missing frames", in.Name)
	}
	out.Hello, out.HelloAck = string(hello), string(ack)
	out.AuthCiphertext, out.AuthOkCiphertext = hex.EncodeToString(authCT), hex.EncodeToString(authOkCT)
	authPT, _ := EncodeControl(control{T: "auth"})
	authOkPT, _ := EncodeControl(control{T: "auth_ok"})
	out.AuthPlaintext, out.AuthOkPlaintext = hex.EncodeToString(authPT), hex.EncodeToString(authOkPT)

	// Independent derivation straight from the spec.
	initEph := key32(t, in.Initiator.EphPriv)
	accEph := key32(t, in.Acceptor.EphPriv)
	initEphPub, _ := curve25519.X25519(initEph[:], curve25519.Basepoint)
	accEphPub, _ := curve25519.X25519(accEph[:], curve25519.Basepoint)
	out.Initiator.EphPub, out.Acceptor.EphPub = hex.EncodeToString(initEphPub), hex.EncodeToString(accEphPub)
	dh1, _ := curve25519.X25519(initEph[:], accEphPub)
	dh2, _ := curve25519.X25519(initID.Priv[:], accEphPub)
	dh3, _ := curve25519.X25519(initEph[:], accID.Pub[:])
	var psk [32]byte
	if in.Pairing {
		psk = DerivePSK(out.Code, initID.ID(), accID.ID())
	}
	tr := Transcript(hello, ack)
	k1, k2 := DeriveKeys(dh1, dh2, dh3, psk, tr)
	out.DH1, out.DH2, out.DH3 = hex.EncodeToString(dh1), hex.EncodeToString(dh2), hex.EncodeToString(dh3)
	out.PSK, out.Transcript = hex.EncodeToString(psk[:]), hex.EncodeToString(tr[:])
	out.KeyInitToAcc, out.KeyAccToInit = hex.EncodeToString(k1[:]), hex.EncodeToString(k2[:])

	// The wire ciphertexts must equal a direct seal with the derived keys.
	c1, _ := newChannel(iRaw, k1, k2, PeerInfo{}, true)
	if got := c1.sendAEAD.Seal(nil, nonceFor(0), authPT, nil); !bytes.Equal(got, authCT) {
		t.Fatalf("vector %s: auth ciphertext on the wire differs from direct derivation", in.Name)
	}
	c2, _ := newChannel(aRaw, k2, k1, PeerInfo{}, false)
	if got := c2.sendAEAD.Seal(nil, nonceFor(0), authOkPT, nil); !bytes.Equal(got, authOkCT) {
		t.Fatalf("vector %s: auth_ok ciphertext on the wire differs from direct derivation", in.Name)
	}
	return out
}

func TestHandshakeVectors(t *testing.T) {
	if *update {
		f := vectorFile{Description: vectorDescription}
		for _, in := range []vector{newVectorInputs("trusted", false), newVectorInputs("pairing", true)} {
			f.Vectors = append(f.Vectors, runVector(t, in))
		}
		data, err := json.MarshalIndent(f, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(filepath.Dir(vectorsPath), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(vectorsPath, append(data, '\n'), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote %s", vectorsPath)
	}
	data, err := os.ReadFile(vectorsPath)
	if err != nil {
		t.Fatalf("read vectors (run with -update to generate): %v", err)
	}
	var f vectorFile
	if err := json.Unmarshal(data, &f); err != nil {
		t.Fatal(err)
	}
	if len(f.Vectors) < 2 {
		t.Fatalf("expected at least 2 vectors, got %d", len(f.Vectors))
	}
	for _, want := range f.Vectors {
		t.Run(want.Name, func(t *testing.T) {
			got := runVector(t, want)
			if got != want {
				gj, _ := json.MarshalIndent(got, "", "  ")
				wj, _ := json.MarshalIndent(want, "", "  ")
				t.Fatalf("vector mismatch\n got: %s\nwant: %s", gj, wj)
			}
			if !want.Pairing && want.PSK != hex.EncodeToString(make([]byte, 32)) {
				t.Fatal("trusted vector must use a zero PSK")
			}
			if want.Pairing && len(want.Code) != 6 {
				t.Fatalf("pairing vector code %q", want.Code)
			}
		})
	}
}
